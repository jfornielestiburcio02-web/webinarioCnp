export type TranslationKey = keyof typeof T.es;

export function pickLang(): Lang {
  try {
    const l = localStorage.getItem('cnp.lang');
    if (l === 'ca' || l === 'es') return l;
  } catch {
    // sin almacenamiento
  }
  return String(typeof navigator !== 'undefined' ? navigator.language : 'es')
    .toLowerCase()
    .startsWith('ca')
    ? 'ca'
    : 'es';
}

export function rankLabel(name: string, lang: Lang): string {
  return lang === 'ca' ? CA_NAMES[name] || name : name;
}

export function getLocale(lang: Lang): string {
  return lang === 'ca' ? 'ca-ES' : 'es-ES';
}

export function fmtDate(iso: string, lang: Lang): string {
  return new Date(iso).toLocaleString(getLocale(lang), {
    dateStyle: 'medium',
    timeStyle: 'short',
  });
}

export function fmtDay(iso: string | null | undefined, fallback = '—'): string {
  const [y, m, d] = String(iso || '').split('-');
  return y && m && d ? `${d.padStart(2, '0')}/${m.padStart(2, '0')}/${y}` : fallback;
}

export function longDay(iso: string | undefined, lang: Lang): string {
  const [y, m, d] = String(iso || '').split('-').map(Number);
  return y && m && d
    ? new Date(y, m - 1, d).toLocaleDateString(getLocale(lang), {
        day: 'numeric',
        month: 'long',
        year: 'numeric',
      })
    : '';
}
